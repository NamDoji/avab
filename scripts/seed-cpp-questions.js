async function main() {
  const course = await p.course.findUnique({
    where: { code: 'CPP-ALGO' },
    include: { subjects: { orderBy: { order: 'asc' } } },
  })

  if (!course) {
    console.error('Course CPP-ALGO not found!')
    process.exit(1)
  }

  console.log(`📚 Course: ${course.name} | Subjects: ${course.subjects.length}`)

  for (const t of TOPICS) {
    const s = course.subjects.find((sub) => sub.order === t.order)
    if (!s) {
      console.log(`⚠️  Skipping order ${t.order} — not found in DB`)
      continue
    }

    const cnt = await p.question.count({ where: { subjectId: s.id } })
    if (cnt > 0) {
      console.log(`⏭️  Skip: ${t.topicName} (${cnt} câu đã có)`)
      continue
    }

    await p.question.createMany({
      data: t.questions.map((q, i) => ({
        subjectId: s.id,
        order: i + 1,
        questionType: q.type,
        content: q.content,
        options: q.options,
        correctAnswer: q.answer,
        explanation: q.explanation,
        points: 1,
      })),
    })
    console.log(`✅  ${t.order}. ${t.topicName} — ${t.questions.length} câu`)
  }

  console.log('\n🏆 Done! Tổng: ' + TOPICS.reduce((s, t) => s + t.questions.length, 0) + ' câu hỏi')
  await p.$disconnect()
}

main().catch((e) => {
  console.error(e.message)
  process.exit(1)
})
